    if not regular.exists():
        regular, bold = (font_dir / 'DejaVuSans.ttf', font_dir / 'DejaVuSans-Bold.ttf')
    pdfmetrics.registerFont(TTFont('Guide', str(regular)))
    pdfmetrics.registerFont(TTFont('GuideBold', str(bold)))
    styles = {
        'T': ParagraphStyle('title', fontName='GuideBold', fontSize=22, leading=26, textColor=colors.HexColor('#173D47'), spaceAfter=17),
        'H': ParagraphStyle('heading', fontName='GuideBold', fontSize=12, leading=16, spaceBefore=10, spaceAfter=6, keepWithNext=True, textColor=colors.HexColor('#173D47')),
        'P': ParagraphStyle('body', fontName='Guide', fontSize=11, leading=15, spaceAfter=7, alignment=TA_LEFT),
        'C': ParagraphStyle('command', fontName='GuideBold', fontSize=10.5, leading=15, textColor=colors.HexColor('#145C64'), backColor=colors.HexColor('#EDF5F4'), borderPadding=7, spaceBefore=6, spaceAfter=13, keepWithNext=True),
    }
    output = ROOT / 'output/pdf' / f'iskra-{name}-guide.pdf'
    output.parent.mkdir(parents=True, exist_ok=True)
    doc = SimpleDocTemplate(str(output), pagesize=A4, rightMargin=42, leftMargin=42, topMargin=55, bottomMargin=43, title='Искра - ' + pages[0][0], author='Искра')
    story = []
    for idx, (title, blocks) in enumerate(pages):
        if idx: story.append(PageBreak())
        story.append(Paragraph(escape(title), styles['T']))
        for kind, value in blocks:
            # No ambiguous dash glyphs in commands or body copy.
            assert not any(c in value for c in '\u2010\u2011\u2012\u2013\u2014')
            story.append(Paragraph(escape(value).replace('\n', '<br/>'), styles[kind]))
    def decorate(canvas, document):
        canvas.setStrokeColor(colors.HexColor('#D3E3E2'))
        canvas.line(42, A4[1]-35, A4[0]-42, A4[1]-35)
        canvas.setFont('Guide', 8)
        canvas.setFillColor(colors.HexColor('#547078'))
        canvas.drawString(42, A4[1]-26, 'ИСКРА  /  ПОНЯТНАЯ ИНСТРУКЦИЯ')
        revision = '11.09.2026'
        canvas.drawString(42, 23, f'Редакция {revision}  •  Актуальная памятка в боте: /info')
        canvas.drawRightString(A4[0]-42, 23, f'{document.page} / {len(pages)}')
    doc.build(story, onFirstPage=decorate, onLaterPages=decorate)
    reader = PdfReader(output)
    assert len(reader.pages) == len(pages), f'{name}: overflow changed page references'
    for page, (title, _) in zip(reader.pages, pages):
        assert title in page.extract_text(), f'Missing heading: {title}'
    print(f'{name}: {len(reader.pages)} pages, {output.stat().st_size} bytes')


  'Администратору:',
  '/ban <MAX_USER_ID> <причина> | /unban <MAX_USER_ID> — блокировка заявителя',
  '/categories — темы; /category_add <КОД> <Название> — добавить тему',
  '/category_on <КОД> | /category_off <КОД> — включить/выключить тему',

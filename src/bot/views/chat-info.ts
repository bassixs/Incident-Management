export async function chatInfoText(services: AppServices, actor: ResolvedActor, chatId: bigint, dialog: boolean): Promise<string> {
  if (dialog) return USER_INFO;
  const chat = actor.workingChat ?? await workingChatFor(services, chatId);
  if (!chat) return [
    'Этот чат пока не настроен как рабочий чат «Искры».',
    `ID чата: ${chatId}. Передайте его администратору бота для подключения.`,
    '/info — информация о чате', '/whoami — ваш MAX ID и ID чата',
    'Жителям: откройте личный диалог с ботом и отправьте /start.',
  ].join('\n');
  const can = (permission: Permission) => hasPermission(actor.roles, permission) || chat.permissions.includes(permission);
  const sections = [`«Искра» — информация о рабочем чате\nВаши права здесь: ${chat.labels.join(', ')}.\nОни доступны участникам автоматически; вручную назначать роль не нужно.`];
  if (chat.distribution) sections.push([
    'Распределение обращений',
    '1. Откройте /queue и возьмите следующее обращение либо работайте с карточкой в чате.',
    '2. Прочитайте обращение, выберите ответственную группу или причину отклонения кнопками.',
    '3. При работе через очередь обращение закрепляется за вами на 15 минут. Коллега получает другое.',
    '«Освободить обращение» возвращает его в общую очередь, если вы не можете продолжить. Само обращение не удаляется.',
    `При большом потоке ориентируйтесь на /queue: в ней сохраняются нераспределённые обращения. Напоминания приходят ежедневно с ${services.config.DISTRIBUTION_WORK_START} до ${services.config.DISTRIBUTION_WORK_END} (${services.config.APP_TIMEZONE}).`,
  ].join('\n'));
  if (chat.groups.length) sections.push([
    `Профильный чат: ${chat.groups.map(group => group.name).join(', ')}`,
    '1. Откройте карточку и выберите действие кнопками: подготовить ответ или запросить уточнение у жителя.',
    '2. После нажатия отправьте текст и при необходимости фото или файлы. Сообщение будет связано с выбранным обращением.',
    chat.groups.every(group => group.bypassReview)
      ? '3. В этом чате ответ отправляется жителю без отдельного согласования.'
      : chat.groups.some(group => group.bypassReview)
      ? '3. Для групп с прямым ответом он отправляется жителю сразу; для остальных — проходит согласование.'
      : '3. Ответ поступит на согласование. При возврате прочитайте замечания и подготовьте исправленный ответ.',
    `Срок решения — ${services.config.INCIDENT_SLA_HOURS} ч. Пока ждём уточнение жителя, срок приостановлен; после уточнения отсчёт продолжается.`,
    'Напоминания помогают найти обращение: используйте ответ на исходную карточку или переход к ней. Если MAX больше не открывает фото, запросите его повторно; для фото ответа используйте кнопку замены.',
    'Обычная переписка не становится ответом жителю: сначала выберите действие в карточке.',
  ].join('\n'));
  if (chat.review) sections.push([
    'Согласование ответов',
    '1. Сверьте обращение жителя с подготовленным ответом и вложениями.',
    '2. Кнопкой согласуйте ответ либо верните на доработку и отправьте замечание по подсказке бота.',
    '3. После согласования бот отправляет ответ жителю. «Ожидает доставки» означает, что отправка ещё не завершена.',
    'При одновременном согласовании двумя сотрудниками повторное действие не создаёт второй ответ.',
  ].join('\n'));
  if (chat.delivery) sections.push([
    'Контроль доставки',
    'Сюда поступают сообщения о сбоях доставки. Проверьте /delivery_status и /delivery_errors.',
    'После устранения причины повторите нужную исходящую отправку командой /delivery_retry <КОД> из списка ошибок.',
    'Ошибки входящей обработки передавайте администратору для проверки: эта команда повторяет только исходящие сообщения.',
  ].join('\n'));
  const commands = ['/info или /help — инструкция для этого чата', '/whoami — ваш ID, права и ID чата'];
  if (can('incident.lookup')) commands.push('/chatid — ID чата', '/incident <НОМЕР> — карточка обращения', '/history <НОМЕР> — история обращения', '/resend <НОМЕР> — повторить недоставленный согласованный ответ');
  if (chat.distribution && can('incident.distribute')) commands.push('/queue — очередь распределения');
  if (can('report.generate')) commands.push('/report — выбрать период; /report 7d — за 7 дней. Второй лист Excel — нерешённые обращения с истёкшим сроком.');
  if (can('delivery.manage')) commands.push('/delivery_status — состояние очередей', '/delivery_errors — проблемы доставки и их коды', '/delivery_retry <КОД> — повторить одну отправку; без кода — все неудачные исходящие');
  sections.push(`Доступные команды:\n${commands.join('\n')}\nПример номера: INC-20260906-0001.`);
  if (can('admin.manage')) sections.push(ADMIN_INFO);
  return sections.join('\n\n');
}

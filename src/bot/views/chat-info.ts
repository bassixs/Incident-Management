import type { AppServices } from '../../app/container';
import { workingChatFor } from '../../users/working-chat';
import type { ResolvedActor } from '../handlers/helpers';

export async function chatInfoText(services: AppServices, actor: ResolvedActor, chatId: bigint, dialog: boolean): Promise<string> {
  if (dialog) return [
    '«Искра» — помощь с обращением', '',
    '1. Отправьте /start и нажмите «Создать обращение».',
    '2. Ответьте на вопросы бота. Можно добавить фото, файлы не принимаются.',
    '3. Проверьте данные и нажмите «Всё верно». Ответ придёт сюда.', '',
    '/my — посмотреть свои обращения', '/rules — правила',
    '/info или /help — эта памятка', '',
    'Ниже — подробная инструкция с примерами.',
  ].join('\n');
  const chat = actor.workingChat ?? await workingChatFor(services, chatId);
  if (!chat) return [
    'Этот чат пока не настроен как рабочий чат «Искры».',
    `Передайте администратору ID чата: ${chatId}.`,
    '/whoami — узнать свой ID',
    'Чтобы подать обращение, откройте личный чат с ботом и отправьте /start.',
  ].join('\n');
  const sections: string[] = [];
  if (chat.distribution) sections.push([
    'Распределение обращений',
    'Здесь решаем, кому поручить обращение.', '',
    '1. Отправьте /queue и возьмите следующее обращение.',
    '2. Прочитайте его, нажмите «Распределить» и выберите организацию.',
    '3. Возьмите следующее. Коллеги могут работать одновременно.', '',
    'Не можете продолжить? «Освободить обращение» вернёт его коллегам в очередь.',
    'Для отчёта: /report в системном чате аналитики.',
  ].join('\n'));
  if (chat.groups.length) sections.push([
    `Профильный чат: ${chat.groups.map(group => group.name).join(', ')}`,
    'Здесь готовим ответы жителям.', '',
    '1. Откройте карточку обращения и нажмите «Взять в работу».',
    '2. Когда ответ готов, нажмите «Подготовить ответ».',
    '3. Отправьте ответ одним сообщением. Фото и файлы прикрепите к нему.', '',
    chat.groups.some(group => !group.bypassReview)
      ? 'Статус вверху карточки: свободное → в работе → на согласовании → отработано.'
      : 'Статус вверху карточки: свободное → в работе → отработано.',
    '«На доработке» — исправьте ответ. «Ожидает доставки» — отправка ещё не подтверждена. «Отработано» — ответ отправлен жителю.', '',
    chat.groups.every(group => group.bypassReview)
      ? 'Ответ отправляется жителю без отдельного согласования.'
      : chat.groups.some(group => group.bypassReview)
        ? 'Порядок отправки зависит от организации: напрямую или после согласования. Бот сообщит результат.'
        : 'Бот передаст ответ на согласование. При возврате исправьте его по замечаниям.',
    `Срок работы с обращением — ${services.config.INCIDENT_SLA_WORKDAYS} рабочих дня. График: пн–пт, ${services.config.WORKDAY_START}–${services.config.WORKDAY_END} МСК. Дедлайн указан в карточке.`,
  ].join('\n'));
  if (chat.review) sections.push([
    'Согласование ответов',
    'Здесь проверяем ответ перед отправкой жителю.', '',
    '1. Прочитайте обращение, ответ и вложения.',
    '2. Всё верно? Нажмите «Согласовать».',
    '3. Нужны исправления? Нажмите «На доработку» и напишите, что исправить.', '',
    '«Ожидает доставки» — житель ещё не получил ответ. Дождитесь подтверждения бота.',
  ].join('\n'));
  if (chat.delivery) sections.push([
    'Аналитика и проблемы доставки',
    'Здесь делаем отчёты и разбираем ошибки отправки.', '',
    '1. Отправьте /report.',
    '2. Выберите период кнопкой.',
    '3. Excel придёт в этот же чат: обращения за период и отдельный лист просроченных.', '',
    'Быстро за неделю: /report 7d.',
    'Есть ошибка? /delivery_errors покажет подробности. Порядок действий — в инструкции ниже.',
    'Только для администраторов бота: /clear_data — удалить обращения за период; /clear_users — сбросить сохранённые данные жителей. Сначала подсчёт, затем отдельное подтверждение.',
  ].join('\n'));
  sections.push('Права для работы здесь уже доступны участникам.\n/info или /help — эта памятка.\nПодробные шаги и примеры команд — в файле по кнопке ниже.');
  return sections.join('\n\n');
}
